// hybrid_bank.h - the read-only view of a hybrid bank image, ported from pmpiano
// (src/core/piano_hybrid.h, bank versions 5 and 6, plus the packed version 7 of this
// repository; the clavinet retune and the parallel executor of the original are not part
// of this port, the harp resonance is)
//
// A hybrid voice (docs of pmpiano: PIANO_HYBRID_PLAN/PIANO_HYBRID_BANK.md) plays a short PCM
// attack from the bank that is crossfaded into a bank of up to 48 freely decaying complex
// modes per key - the sustain is computed, not sampled. Above the highest mode a high-band
// loop (band pieces of the attack, loop points fitted to the band partials) carries the
// treble. The bank carries the fit: poles, initial states per velocity, attack PCM, loop
// data, damper times. synthkeys embeds the image as a byte array (hybrid_splendid_bank.cpp,
// generated by tools/samples/embed_bank.py); a bank plays at its own rate only.
#pragma once

#include <cstddef>
#include <cstdint>
#include <memory>
#include <string>
#include <vector>

#include "config.h"

namespace pmp {

constexpr int kHybridModes = 48;      // modes per key in the bank (a key may use fewer)
constexpr int kHybridLayers = 4;      // version 4: PP MP MF FF, anchors 40 76 92 114
constexpr int kHybridMaxLayers = 5;   // version 5: up to five layers
constexpr int kHybridVelocities = 127;
constexpr int kHybridLoopBands = 8;   // half-octave bands of the loop at most
constexpr int kHybridMaxVelocityAnchors = 32;   // version 7: stored rows of the velocity tables

struct HybridKeyRec {                 // as written by the bank builder (64 byte stride)
    uint16_t modes, damped;
    float f0, releaseT60, trimDb;
    double pcmScale[kHybridMaxLayers];   // int16 -> amplitude, per layer
    uint32_t nE, nAtt;                // the crossfade of this key: N_e .. N_att
};

struct HybridLoopRec5 {               // the loop of a key (248 bytes, 256 byte stride); bands == 0: no loop
    uint16_t bands, seam;
    float split;                      // [Hz] 3 % above the highest mode; bands below it are gap bands
    float lo[kHybridLoopBands], hi[kHybridLoopBands];   // [Hz] per band
    uint32_t seg0, segLen;            // the band pieces cover the attack samples seg0 .. seg0 + segLen of this key
    uint32_t pcmOffset;               // bytes into the loop PCM: [layer][band][segLen] int16
    uint32_t velOffset;               // floats into the velocity section: rows x per band (start, len, phase, a1, s1, a2, s2)
    float scale[kHybridMaxLayers][kHybridLoopBands];
};

// The metadata block of a version 6 bank (1024 bytes after the header): what the bank is.
struct HybridBankMeta {
    enum Type { Unknown = 0, Tine, Reed, Clav, Acoustic, ElectricGrand, Upright, Harpsichord };
    int type = Unknown;
    uint32_t flags = 0;               // bit 0: the layers carry their dynamics (law "rec"), bit 1: the type was measured
    uint32_t date = 0;                // yyyymmdd of the build
    std::string id;                   // short name [a-z0-9_-]: the instrument id
    std::string name;                 // display name, UTF-8
    std::string base;                 // the preset the bank plays in
    std::string source;               // origin and licence of the samples, UTF-8
    std::string tool;                 // what built it
    std::string overlay;              // lines name=value of public parameters over the base preset
};

// Validated read-only view of a bank image in memory (the caller keeps the memory alive, 16-byte aligned).
class HybridBank {
public:
    bool attach(const uint8_t* data, size_t size, std::string* err = nullptr);
    bool valid() const { return keys_ != nullptr; }

    int rate() const { return rate_; }
    const HybridBankMeta& meta() const { return meta_; }
    int firstKey() const { return first_; }
    int lastKey() const { return last_; }
    int attackFrames() const { return nAtt_; }      // N_att (the longest)
    int fadeStart() const { return nE_; }           // N_e (of the first key)
    int attackFrames(int note) const;               // N_att of a key
    int fadeStart(int note) const;                  // N_e of a key
    int layers() const { return nLay_; }
    int anchor(int layer) const { return anchors_[layer]; }
    double level() const { return level_; }         // the loudness law: attack RMS = level (v/refVel)^gamma
    double refVel() const { return refVel_; }
    double gamma() const { return gamma_; }
    double rampMs() const { return rampMs_; }       // damper felt compression time
    double pedalLost() const { return pedalLost_; } // CC64/127 below this keeps the dampers fully on
    double pedalFull() const { return pedalFull_; } // CC64/127 above this lifts them fully off
    const HybridKeyRec& key(int note) const { return *reinterpret_cast<const HybridKeyRec*>(keys_ + size_t(idx(note)) * kKeyStride); }   // 64 byte stride in the image
    const double* poles(int note) const { return poles_ + size_t(idx(note)) * kHybridModes * 2; }          // (sigma [1/s], omega [rad/s]) per mode
    // The velocity tables: version 5/6 store all 127 rows, version 7 stores `velocityAnchors()`
    // rows and these fill versions interpolate linearly between them (the player uses them).
    int velocityAnchors() const { return nVel_; }       // 127 for versions 5/6
    int velocityAnchor(int i) const { return velAnchor_[i]; }
    int loopVelocityRows() const { return loopRows_; }  // 127 (exact) or the state anchors
    void states(int note, int vel, float* out) const;               // 2 * modes: (re, im)
    void filter(int note, int vel, double* out) const;              // 5: b0 b1 b2 a1 a2
    const float* states(int note, int vel) const;                   // the stored row at or below vel (version 7: an anchor, prefer the fill version)
    const double* filter(int note, int vel) const;                  // the stored row at or below vel
    const int16_t* pcm(int note, int layer) const { return pcm_ + pcmOff_[size_t(idx(note))] + size_t(layer) * size_t(attackFrames(note)); }
    const char* revision() const { return revision_; }   // source revision of the fit
    const char* state() const { return state_; }         // name of the fit state
    int version() const { return version_; }

    // --- the high-band loop
    bool hasLoop() const { return loopKeys_ != nullptr; }
    int loopBands(int note) const;                    // 0: no loop on this key
    int loopSeam(int note) const;
    int loopSegLength(int note) const;
    float loopScale(int note, int layer, int band) const;
    const int16_t* loopPcm(int note, int layer, int band) const;
    void loopVelocity(int note, int vel, float* out) const;         // 7 * loopBands(note) floats
    const float* loopVelocity(int note, int vel) const;             // the stored row at or below vel

public:
    static constexpr size_t kKeyStride = 64;
    static constexpr size_t kLoopStride5 = 256;

private:
    int idx(int note) const { return (note < first_ ? first_ : note > last_ ? last_ : note) - first_; }
    const HybridLoopRec5* loop5(int note) const;
    void velocityRow(int vel, int& i0, int& i1, float& t) const;   // the two stored rows around vel and the weight of i1
    int rate_ = 0, first_ = 0, last_ = 0, nAtt_ = 0, nE_ = 0, nLay_ = kHybridLayers, anchors_[kHybridMaxLayers] = {};
    int nVel_ = kHybridVelocities, filterRows_ = 0, loopRows_ = kHybridVelocities;   // version 7: stored rows
    uint8_t velAnchor_[kHybridMaxVelocityAnchors] = {};
    double level_ = 0, refVel_ = 1, gamma_ = 0, rampMs_ = 10, pedalLost_ = 0.5, pedalFull_ = 0.85;
    const uint8_t* keys_ = nullptr;
    const double* poles_ = nullptr;
    const float* z_ = nullptr;
    const double* filt_ = nullptr;
    const int16_t* pcm_ = nullptr;
    const uint8_t* loopKeys_ = nullptr;
    const uint8_t* loopPcm_ = nullptr;
    const float* loopVel_ = nullptr;
    int version_ = 0;
    char revision_[41] = {}, state_[25] = {};
    HybridBankMeta meta_;
    std::vector<size_t> pcmOff_;          // first PCM frame of each key (rows of the key's own N_att)
};

// Voicing of the hybrid voice on the poles of the bank, live and without allocation (pmpiano
// docs PIANO_HYBRID_PIANOTEQ_REVIEW.md P8); the states are not touched, so the crossfade from
// the attack stays continuous (keep unison and stretch small: the attack PCM is not retuned).
// All zero: bit-identical to the bank.
struct HybridVoicing {
    double decay = 0;                     // [%] T60 of every mode x 2^(decay/100)
    double unison = 0;                    // [%] spread of the modes of one partial (within 1 % of each other): x (1 + unison/100)
    double stretch = 0;                   // [cent per octave] about C4, on the poles of a key
    double hardness = 0;                  // [%] +100 = the timbre of 32 velocity steps harder (layers, filter, states, loop); the level follows the played velocity
};

// The resonance bank ("harp", pmpiano docs/PIANO_HYBRID_RESONANCE.md section 4): per key a
// second set of its first `modes` modes, driven by the dry output of all other keys, never
// by its own, and added to the output. Nothing feeds back, so it is stable for any gain.
struct HybridResonance {
    bool   on = false;                            // off: the player is bit-identical to one without the harp
    double gain = 0;                              // input weight of a mode at the key's f0 (the coupling)
    int    modes = 16;                            // modes per key (at most the key's own)
    double tiltDb = 0;                            // [dB per octave] of the input weight above the key's f0
    bool   undamped = true;                       // keys without a damper ring along without the pedal too
};

struct HybridParams {
    double level = -1, refVel = -1, gamma = -1;   // < 0: from the bank
    int    attackSlots = 178;                     // two per key (20 Hz repetition at 100 ms)
    int    fadePool = 16;                         // slots for attacks that are faded out (overload)
    double stealFadeMs = 5.0;
    double sleepEnergy = 1e-12;                   // a key sleeps when sum |z|^2 stays below this (about -120 dB)
    double rampMs = -1, pedalLost = -1, pedalFull = -1;   // < 0: from the bank
    HybridResonance res;
};

class HybridPlayer {
public:
    HybridPlayer();
    ~HybridPlayer();
    HybridPlayer(const HybridPlayer&) = delete;
    HybridPlayer& operator=(const HybridPlayer&) = delete;

    // Not real-time safe. The bank has a fixed rate: another host rate is refused (no guessing).
    bool prepare(double fs, const HybridBank& bank, const HybridParams& p = HybridParams());
    // The harp: the strings that ring along. Switching it on or off clears its state; off,
    // the player is bit-identical to one without it (pmpiano's setResonance).
    void setResonance(const HybridResonance& r);
    // The damper's felt time and the pedal curve, live and without allocation: a value <= 0
    // (rampMs) or < 0 (pedalLost, pedalFull) keeps the bank's.
    void setDamper(double rampMs, double pedalLost, double pedalFull);
    // T60 [s] of a key under its damper, indexed by MIDI note 0..127; nullptr: the bank's values.
    void setReleaseT60(const float* t60ByNote);
    // The slow phase under the damper: a share `share` of a key's amplitude (the polarisation
    // the felt does not reach) decays with T60 `slowT60` [s] while the rest decays with the
    // key's release T60; share 0 keeps the single phase bit for bit.
    void setSlowPhase(double share, double slowT60);
    // dB added to the bank's loudness law per MIDI velocity 0..127; nullptr: the law alone.
    void setVelocityGain(const float* dbByVelocity);
    void setVoicing(const HybridVoicing& v);
    // The voice limit: at most n keys sound (0 = all). A strike of a key that does not sound
    // makes room: the quietest sounding key gives up - a released one before a held or
    // pedalled one, a key in its attack last - and fades out within 20 ms.
    void setMaxKeys(int n);

    void noteOn(int note, int velocity);
    void noteOff(int note);
    void controller(int cc, int value);            // 64 sustain pedal, 120 sound off, 123 notes off
    void allSoundOff();                            // a 5 ms fade of everything, then silence
    void reset();                                  // hard: silence at once, like a freshly prepared player
    void process(float* out, int nFrames);         // mono, overwritten

    int attackVoices() const;                      // attacks in progress (the first 100 ms of a strike)
    int sustainingKeys() const;                    // keys with a sounding mode state or loop
    int loops() const;                             // high-band loops sounding (active and fading out)
    long stolen() const { return stolen_; }        // attacks faded out for lack of a slot
    long dropped() const { return dropped_; }      // attacks lost for lack of a fade slot
    double gainOf(int velocity) const;

private:
    struct Impl;
    std::unique_ptr<Impl> d_;
    long stolen_ = 0, dropped_ = 0;
};

} // namespace pmp
